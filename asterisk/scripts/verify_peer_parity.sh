#!/usr/bin/env bash
# Compare a local Asterisk peer against a report captured on the other peer.
# This script never changes configuration. By default it does issue the normal
# Asterisk "dialplan reload" command; pass --no-dialplan-reload for a strictly
# read-only report. Asterisk has no native "dry-run dialplan reload" CLI command.
# For Git/live file checksum drift detection, run check_config_drift.sh first;
# this script compares runtime version, module, and dialplan signatures.

set -euo pipefail

ASTERISK_BIN="${ASTERISK_BIN:-asterisk}"
OUTPUT=""
REFERENCE=""
RELOAD_DIALPLAN=1

usage() {
  cat <<'EOF'
Usage: verify_peer_parity.sh [--output FILE] [--reference FILE] [--no-dialplan-reload]

Run once on each PBX:
  sudo ./verify_peer_parity.sh --output /var/tmp/asterisk-1-parity.env
  sudo ./verify_peer_parity.sh --output /var/tmp/asterisk-2-parity.env \
    --reference /secure-transfer/asterisk-1-parity.env

The default runs "asterisk -rx 'dialplan reload'", which is a real but normal
reload, not a dry run. Use --no-dialplan-reload for a read-only CLI check.

For shared configuration checksums and file-level reports, run
check_config_drift.sh before comparing these runtime reports.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --output) OUTPUT="${2:?--output requires a file}"; shift 2 ;;
    --reference) REFERENCE="${2:?--reference requires a file}"; shift 2 ;;
    --no-dialplan-reload) RELOAD_DIALPLAN=0; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

command -v "${ASTERISK_BIN}" >/dev/null 2>&1 || {
  echo "Asterisk CLI not found: ${ASTERISK_BIN}" >&2
  exit 2
}

if [[ -z "${OUTPUT}" ]]; then
  OUTPUT="./asterisk-peer-parity-$(hostname -s)-$(date +%Y%m%d%H%M%S).env"
fi

tmpdir="$(mktemp -d)"
trap 'rm -rf "${tmpdir}"' EXIT

run_cli() {
  local command="$1"
  "${ASTERISK_BIN}" -rx "${command}"
}

run_cli "core show version" >"${tmpdir}/version.txt"
run_cli "module show" >"${tmpdir}/modules.txt"
run_cli "dialplan show" >"${tmpdir}/dialplan.txt"

if [[ "${RELOAD_DIALPLAN}" -eq 1 ]]; then
  run_cli "dialplan reload" >"${tmpdir}/dialplan-reload.txt"
  reload_status="executed"
else
  printf 'not executed (--no-dialplan-reload)\n' >"${tmpdir}/dialplan-reload.txt"
  reload_status="not-executed"
fi

# Compare stable identities rather than variable descriptions/use counts.
version="$(awk '/Asterisk/ { print; exit }' "${tmpdir}/version.txt")"
module_hash="$(awk '$1 ~ /\.so$/ {print $1}' "${tmpdir}/modules.txt" | LC_ALL=C sort | sha256sum | awk '{print $1}')"
dialplan_hash="$(sha256sum "${tmpdir}/dialplan.txt" | awk '{print $1}')"
reload_result="$(tr '\n' ' ' <"${tmpdir}/dialplan-reload.txt" | sed 's/[[:space:]]\+/ /g')"

{
  printf 'HOST=%q\n' "$(hostname -f 2>/dev/null || hostname)"
  printf 'COLLECTED_AT=%q\n' "$(date -u +%FT%TZ)"
  printf 'ASTERISK_VERSION=%q\n' "${version}"
  printf 'MODULE_LIST_SHA256=%q\n' "${module_hash}"
  printf 'DIALPLAN_SHOW_SHA256=%q\n' "${dialplan_hash}"
  printf 'DIALPLAN_RELOAD=%q\n' "${reload_status}"
  printf 'DIALPLAN_RELOAD_RESULT=%q\n' "${reload_result}"
} >"${OUTPUT}"

echo "Wrote parity report: ${OUTPUT}"
echo "  version: ${version}"
echo "  modules: ${module_hash}"
echo "  dialplan: ${dialplan_hash}"
echo "  dialplan reload: ${reload_status}"

if [[ -n "${REFERENCE}" ]]; then
  [[ -r "${REFERENCE}" ]] || { echo "Reference report is unreadable: ${REFERENCE}" >&2; exit 2; }
  # Reports are generated by this script. Do not source arbitrary untrusted files.
  get_value() {
    local key="$1" file="$2"
    awk -F= -v key="${key}" '$1 == key {sub(/^[^=]*=/, ""); gsub(/^'\''|'\''$/, ""); print; exit}' "${file}"
  }

  failed=0
  for key in ASTERISK_VERSION MODULE_LIST_SHA256 DIALPLAN_SHOW_SHA256; do
    local_value="$(get_value "${key}" "${OUTPUT}")"
    reference_value="$(get_value "${key}" "${REFERENCE}")"
    if [[ "${local_value}" == "${reference_value}" && -n "${local_value}" ]]; then
      echo "PASS ${key}"
    else
      echo "FAIL ${key}: local=${local_value:-<missing>} reference=${reference_value:-<missing>}" >&2
      failed=1
    fi
  done
  exit "${failed}"
fi
