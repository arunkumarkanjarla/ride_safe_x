def registry_js(res):
    """Screen registry for the prototype runtime: id -> app, file, title, next screens, previous screens."""
    reg = {}
    for app, (order, by) in res.items():
        for sid in order:
            reg[sid] = {"app": app, "file": sfile(sid), "title": stitle(sid), "to": by[sid].get("to", []), "from": []}
    for sid, v in reg.items():
        for t in v["to"]:
            if t in reg and sid not in reg[t]["from"]:
                reg[t]["from"].append(sid)
    os.makedirs(f"{OUT}/assets/js/generated", exist_ok=True)
    with open(f"{OUT}/assets/js/generated/screens.js", "w", encoding="utf-8", newline="\n") as f:
        f.write("/* GENERATED by source/build.py from source/registry.py and the screen specs. Do not edit by hand. */\n"
                "window.RN_SCREENS = " + json.dumps(reg, ensure_ascii=False, separators=(",", ":")) + ";\n")

