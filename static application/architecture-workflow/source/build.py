def source_copy():
    dst = f"{OUT}/source"
    if os.path.abspath(dst) == GEN:
        return
    os.makedirs(dst, exist_ok=True)
    for f in glob.glob(f"{GEN}/*.py") + [f"{GEN}/site.css", f"{GEN}/mock.css", f"{GEN}/README.txt"]:
        if os.path.basename(f) in ("t.py", "quick.py", "quick_r.py", "quick_s.py"):
            continue
        shutil.copy(f, dst)

