def architecture():
    archlib.ARCH_PAGES.clear()
    built = []
    for m in (arch_a, arch_b, arch_c, arch_d, arch_e):
        for f in m.PAGES:
            fname, title, body, desc = f()
            built.append((fname, title, body, desc))
    meta = [(fn, fn[:2], t, d) for fn, t, b, d in built]
    for i, (fn, t, b, d) in enumerate(built):
        prev = meta[i-1] if i > 0 else None
        nxt = meta[i+1] if i < len(meta)-1 else None
        archlib.finish(fn, t, b, (prev[0], prev[1], prev[2]) if prev else None, (nxt[0], nxt[1], nxt[2]) if nxt else None)
    tiles = "".join(f'<a class="tile" href="{fn}"><span class="n">{n}</span><b>{t}</b><span>{esc(d)}</span></a>' for fn, n, t, d in meta)
    body = (f'<div class="head"><div class="crumbs"><a href="../index.html">Home</a> / Architecture</div><div class="eyebrow">Architecture</div>'
            f'<h1>Architecture blueprint</h1><p class="lead">{len(meta)} pages, from a plain-language walkthrough to multi-service travel, offline areas, global launch, data, security and compliance. Every diagram is also saved as an image in the images folder.</p></div>'
            f'<section><div class="grid">{tiles}</div></section>'
            f'<section><div class="head"><div class="eyebrow">Reference</div><h2>Original concept image</h2></div><figure><div class="diagram"><img src="../images/reference/reference-architecture.png" alt="Reference architecture" style="width:100%;display:block"></figure></section>')
    write("architecture/index.html", page("Architecture", body, "../", "arch"))
    return meta

