"""Post-processing applied by components.write() to every generated HTML page.

Moves every inline style attribute into a generated stylesheet so the pages can run under a
Content Security Policy without 'unsafe-inline'. The screen generators keep their readable
f-strings; this step guarantees a rebuild never reintroduces inline CSS.

How styles become classes
* Each declaration becomes one reusable atomic class, e.g. style="font-weight:700" -> class
  "x-font-weight-700". The same declaration anywhere in the site shares the class.
* An inline style always beat the element's other rules, so every generated rule is marked
  !important to keep exactly that precedence (the hand-written CSS uses no !important).
* When one style attribute mixes a shorthand with its own longhand (e.g. padding + padding-top)
  or repeats a property, the declaration order matters, so the whole block becomes a single
  class "xb-<hash>" that keeps the original order.

The generated file is assets/css/generated/extracted.css. Do not edit it by hand.
"""
import hashlib
import re

import htmltree

_ATOMS = {}      # class name -> declaration text
_BLOCKS = {}     # class name -> list of declarations
_BY_DECL = {}    # declaration text -> class name


def _split(style):
    out, buf, depth, quote = [], [], 0, None
    for ch in style:
        if quote:
            buf.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in "\"'":
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == ";" and depth == 0:
            out.append("".join(buf)); buf = []
            continue
        buf.append(ch)
    out.append("".join(buf))
    decls = []
    for d in out:
        if ":" not in d:
            continue
        p, v = d.split(":", 1)
        p, v = p.strip().lower(), v.replace("!important", "").strip()
        if p and v:
            decls.append((p, v))
    return decls


_SHORT = {"inset": {"top", "right", "bottom", "left"}, "gap": {"row-gap", "column-gap"},
          "flex": {"flex-grow", "flex-shrink", "flex-basis"}, "overflow": {"overflow-x", "overflow-y"},
          "place-items": {"align-items", "justify-items"}, "place-content": {"align-content", "justify-content"}}


def _overlap(a, b):
    if a == b or a.startswith(b + "-") or b.startswith(a + "-"):
        return True
    return b in _SHORT.get(a, ()) or a in _SHORT.get(b, ())


def _slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def _h(s, n=6):
    return hashlib.sha1(s.encode("utf-8")).hexdigest()[:n]


def _atom(p, v):
    decl = f"{p}:{v}"
    if decl in _BY_DECL:
        return _BY_DECL[decl]
    vs = _slug(v)
    if not vs or len(vs) > 24:
        vs = (vs[:14] + "-" if vs else "") + _h(decl)
    name = f"x-{_slug(p)}-{vs}"
    if name in _ATOMS and _ATOMS[name] != decl:
        name += "-" + _h(decl)
    _ATOMS[name] = decl
    _BY_DECL[decl] = name
    return name


def classes_for(style):
    decls = _split(style)
    if not decls:
        return []
    props = [p for p, _ in decls]
    mixed = any(_overlap(props[i], props[j]) for i in range(len(props)) for j in range(i + 1, len(props)))
    if not mixed:
        return [_atom(p, v) for p, v in decls]
    key = ";".join(f"{p}:{v}" for p, v in decls)
    name = "xb-" + _h(key, 8)
    _BLOCKS[name] = decls
    return [name]


def extract_styles(root):
    for n in root.iter():
        st = n.get("style")
        if st is None:
            continue
        n.remove("style")
        n.add_class(*classes_for(st))
    return root


def process(text):
    root = htmltree.parse(text)
    extract_styles(root)
    return root.serialize()


def stylesheet():
    lines = ["/* GENERATED by source/postprocess.py from the generators' inline styles. Do not edit by hand. */",
             "/* !important keeps the precedence the inline style attribute had. */"]
    for name in sorted(_ATOMS):
        p, v = _ATOMS[name].split(":", 1)
        lines.append(f".{name}{{{p}:{v} !important}}")
    for name in sorted(_BLOCKS):
        body = ";".join(f"{p}:{v} !important" for p, v in _BLOCKS[name])
        lines.append(f".{name}{{{body}}}")
    return "\n".join(lines) + "\n"


def reset():
    _ATOMS.clear(); _BLOCKS.clear(); _BY_DECL.clear()
